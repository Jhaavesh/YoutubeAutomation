"""Locally synthesized, original background music for the channel.

Why this exists
---------------
The old ``assets/audio/phonk_1.mp3`` matched a third-party Content ID claim
("Infraction - Don't Care").  Downloading a "royalty-free" track is also not a
guarantee: the same recording can be registered by someone else later.

This module creates a beat from scratch with sine/noise oscillators.  It does
not download, sample, or copy any existing recording, so the output is original
and cannot be matched to a third-party master recording by Content ID.

Usage:
    python audio_factory.py
    python audio_factory.py --styles action,nightlife --duration 32
    python audio_factory.py --force

Tracks are grouped by mood so the renderer can match the music to the topic:
``action`` (chases, stunts, explosions), ``nightlife`` (neon/car-meet),
``tension`` (wildlife, sewers, sharks) and ``fun`` (taxi/NPC comedy).
"""
from __future__ import annotations

import argparse
import array
import logging
import math
import os
import random
import subprocess
import tempfile
import wave
from typing import List, Optional

log = logging.getLogger("audio_factory")

SAMPLE_RATE = 44100
DEFAULT_DURATION = 32.0
DEFAULT_BPM = 140.0

# Each style has its own filename prefix and base tempo.  ``count`` is how
# many variations are generated by default.
STYLE_PRESETS = {
    "action": {"prefix": "original_phonk", "bpm": 150.0, "step": 2.0, "count": 3},
    "nightlife": {
        "prefix": "original_nightlife",
        "bpm": 116.0,
        "step": 2.0,
        "count": 2,
    },
    "tension": {
        "prefix": "original_tension",
        "bpm": 90.0,
        "step": 2.0,
        "count": 2,
    },
    "fun": {"prefix": "original_fun", "bpm": 122.0, "step": 2.0, "count": 2},
}
VALID_STYLES = tuple(STYLE_PRESETS)

# Note palette (Hz).  Action/tension use F minor; fun uses F major pentatonic.
F1, G1, AB1, A1, B1, C2, D2, EB2 = (
    43.65,
    49.00,
    51.91,
    55.00,
    61.74,
    65.41,
    73.42,
    77.78,
)
F3, G3, AB3, A3, B3, C4, EB4 = (
    174.61,
    196.00,
    207.65,
    220.00,
    246.94,
    261.63,
    311.13,
)
F4, G4, AB4, A4, B4, C5, D5, EB5 = (
    349.23,
    392.00,
    415.30,
    440.00,
    493.88,
    523.25,
    587.33,
    622.25,
)


def _add_kick(mix: List[float], start: int, amp: float, sr: int) -> None:
    """Deep 808-style kick with a short pitch sweep."""
    n = min(int(0.38 * sr), len(mix) - start)
    phase = 0.0
    for i in range(n):
        t = i / sr
        freq = 45.0 + 105.0 * math.exp(-t * 28.0)
        phase += 2.0 * math.pi * freq / sr
        env = math.exp(-t * 11.0)
        click = math.exp(-t * 120.0) * 0.35
        mix[start + i] += amp * (math.sin(phase) * env + click)


def _add_snare(
    mix: List[float], start: int, amp: float, sr: int, rng: random.Random
) -> None:
    """Noise snare with a small tonal body."""
    n = min(int(0.22 * sr), len(mix) - start)
    prev = 0.0
    for i in range(n):
        t = i / sr
        noise = rng.uniform(-1.0, 1.0)
        high = noise - prev  # crude high-pass to keep the snare crisp
        prev = noise
        env = math.exp(-t * 26.0)
        body = math.sin(2.0 * math.pi * 185.0 * t) * math.exp(-t * 30.0) * 0.5
        mix[start + i] += amp * (high * env * 0.7 + body)


def _add_hat(
    mix: List[float],
    start: int,
    amp: float,
    sr: int,
    rng: random.Random,
    open_hat: bool = False,
) -> None:
    """Short closed hat or a longer open hat."""
    duration = 0.18 if open_hat else 0.055
    n = min(int(duration * sr), len(mix) - start)
    prev = 0.0
    decay = 14.0 if open_hat else 70.0
    for i in range(n):
        t = i / sr
        noise = rng.uniform(-1.0, 1.0)
        high = noise - prev
        prev = noise
        mix[start + i] += amp * high * math.exp(-t * decay)


def _add_bass(
    mix: List[float], start: int, freq: float, amp: float, sr: int
) -> None:
    """Punchy 808 bass note with a short pitch drop."""
    duration = 0.55
    n = min(int(duration * sr), len(mix) - start)
    phase = 0.0
    for i in range(n):
        t = i / sr
        current = freq * (1.0 + 0.06 * math.exp(-t * 30.0))
        phase += 2.0 * math.pi * current / sr
        env = math.exp(-t * 3.2)
        tone = (
            math.sin(phase)
            + 0.28 * math.sin(2.0 * phase)
            + 0.12 * math.sin(3.0 * phase)
        )
        mix[start + i] += amp * tone * env


def _add_cowbell(
    mix: List[float], start: int, freq: float, amp: float, sr: int
) -> None:
    """Metallic cowbell accent."""
    n = min(int(0.28 * sr), len(mix) - start)
    for i in range(n):
        t = i / sr
        env = math.exp(-t * 11.0)
        tone = math.sin(2.0 * math.pi * freq * t) + 0.55 * math.sin(
            2.0 * math.pi * freq * 2.4 * t
        )
        mix[start + i] += amp * tone * env


def _add_pad_chord(
    mix: List[float],
    sr: int,
    freqs: List[float],
    amp: float = 0.055,
    lfo_rate: float = 0.07,
) -> None:
    """Quiet, slowly breathing chord under the drums."""
    if not freqs:
        return
    n = len(mix)
    for i in range(n):
        t = i / sr
        lfo = 0.55 + 0.45 * math.sin(2.0 * math.pi * lfo_rate * t)
        chord = sum(
            math.sin(2.0 * math.pi * freq * t) for freq in freqs
        ) / len(freqs)
        mix[i] += amp * chord * lfo


def _add_pad(mix: List[float], sr: int) -> None:
    """Dark F-minor pad used by the action/phonk tracks."""
    _add_pad_chord(mix, sr, [F3, AB3, C4])


def _add_drone(
    mix: List[float],
    sr: int,
    freqs: List[float],
    amp: float = 0.10,
    tremolo_rate: float = 0.05,
) -> None:
    """Sustained low drone for suspense/tension beds."""
    if not freqs:
        return
    n = len(mix)
    for i in range(n):
        t = i / sr
        lfo = 0.60 + 0.40 * math.sin(2.0 * math.pi * tremolo_rate * t)
        tone = sum(
            math.sin(2.0 * math.pi * freq * t) for freq in freqs
        ) / len(freqs)
        mix[i] += amp * tone * lfo


def _add_pluck(
    mix: List[float],
    start: int,
    freq: float,
    amp: float,
    sr: int,
    decay: float = 9.0,
) -> None:
    """Short saw-like synth pluck for nightlife/fun melodies."""
    n = min(int(0.35 * sr), len(mix) - start)
    if n <= 0:
        return
    for i in range(n):
        t = i / sr
        env = math.exp(-t * decay)
        tone = sum(
            math.sin(2.0 * math.pi * freq * harmonic * t) / harmonic
            for harmonic in range(1, 6)
        )
        mix[start + i] += amp * 0.5 * tone * env


def _add_noise_sweep(
    mix: List[float],
    start: int,
    duration: float,
    amp: float,
    sr: int,
    rng: random.Random,
) -> None:
    """Rising filtered-noise swell used in the tension style."""
    n = min(int(duration * sr), len(mix) - start)
    if n <= 0:
        return
    prev = 0.0
    for i in range(n):
        noise = rng.uniform(-1.0, 1.0)
        high = noise - prev
        prev = noise
        progress = i / n
        env = (progress ** 2) * (1.0 - progress)
        mix[start + i] += amp * 4.0 * high * env


def _add_stab_bass(
    mix: List[float],
    start: int,
    freq: float,
    amp: float,
    sr: int,
    duration: float = 0.20,
    decay: float = 13.0,
) -> None:
    """Short, driving bass stab for the action-thriller score."""
    n = min(int(duration * sr), len(mix) - start)
    if n <= 0:
        return
    phase = 0.0
    for i in range(n):
        t = i / sr
        current = freq * (1.0 + 0.05 * math.exp(-t * 35.0))
        phase += 2.0 * math.pi * current / sr
        env = math.exp(-t * decay)
        tone = (
            math.sin(phase)
            + 0.30 * math.sin(2.0 * phase)
            + 0.12 * math.sin(3.0 * phase)
        )
        mix[start + i] += amp * tone * env


def _add_string_stab(
    mix: List[float],
    start: int,
    freqs: List[float],
    amp: float,
    sr: int,
    duration: float = 0.24,
    decay: float = 9.0,
) -> None:
    """Saw-like orchestral stab used for cinematic accents."""
    if not freqs:
        return
    n = min(int(duration * sr), len(mix) - start)
    if n <= 0:
        return
    for i in range(n):
        t = i / sr
        env = math.exp(-t * decay)
        tone = 0.0
        for freq in freqs:
            tone += sum(
                math.sin(2.0 * math.pi * freq * harmonic * t) / harmonic
                for harmonic in range(1, 5)
            )
        mix[start + i] += amp * 0.5 * (tone / len(freqs)) * env


def _finalize(mix: List[float], sr: int) -> List[float]:
    """Normalize to a musical RMS, respect the peak, and fade in/out."""
    n = len(mix)
    peak = max(abs(sample) for sample in mix) or 1.0
    rms = math.sqrt(sum(sample * sample for sample in mix) / max(1, n)) or 1.0
    gain = min(0.16 / rms, 0.95 / peak)
    fade = max(1, int(0.08 * sr))
    for i in range(n):
        value = mix[i] * gain
        if i < fade:
            value *= i / fade
        elif i >= n - fade:
            value *= (n - i) / fade
        mix[i] = max(-1.0, min(1.0, value))
    return mix


def _add_crackle(
    mix: List[float], sr: int, rng: random.Random, density: float = 0.00012
) -> None:
    """Sparse vinyl-style crackle for texture."""
    n = len(mix)
    for i in range(n):
        if rng.random() >= density:
            continue
        amp = rng.uniform(0.01, 0.05)
        length = min(int(0.01 * sr), n - i)
        for j in range(length):
            mix[i + j] += amp * math.exp(-j / (0.002 * sr)) * (
                1.0 if j % 2 == 0 else -1.0
            )


def synthesize_phonk(
    duration: float = DEFAULT_DURATION,
    bpm: float = DEFAULT_BPM,
    seed: int = 1,
    sample_rate: int = SAMPLE_RATE,
) -> List[float]:
    """Return a mono float sample buffer in the range [-1, 1]."""
    n = int(duration * sample_rate)
    mix = [0.0] * n
    rng = random.Random(seed)

    step_duration = 60.0 / bpm / 4.0  # one 16th note
    steps = int(duration / step_duration)

    kick_steps = {0, 6, 8, 14}
    snare_steps = {4, 12}
    bass_pattern = {0: F1, 3: F1, 6: AB1, 8: C2, 11: AB1, 14: EB2}
    bell_pattern = {2: F4, 7: AB4, 10: C5, 15: F4}

    for step in range(steps):
        start = int(step * step_duration * sample_rate)
        if start >= n:
            break
        bar_step = step % 16

        if bar_step in kick_steps:
            _add_kick(mix, start, 0.95, sample_rate)
        if bar_step in snare_steps:
            _add_snare(mix, start, 0.55, sample_rate, rng)
        if bar_step % 2 == 0:
            _add_hat(
                mix,
                start,
                0.22,
                sample_rate,
                rng,
                open_hat=(bar_step == 14),
            )
        if bar_step in bass_pattern:
            _add_bass(mix, start, bass_pattern[bar_step], 0.75, sample_rate)
        if bar_step in bell_pattern:
            _add_cowbell(mix, start, bell_pattern[bar_step], 0.16, sample_rate)

    _add_pad(mix, sample_rate)
    _add_crackle(mix, sample_rate, rng)
    return _finalize(mix, sample_rate)


def synthesize_action_thriller(
    duration: float = DEFAULT_DURATION,
    bpm: float = 150.0,
    seed: int = 1,
    sample_rate: int = SAMPLE_RATE,
) -> List[float]:
    """Cinematic action-thriller score for chases, heists and shootouts.

    Driving staccato bass, orchestral string stabs, 16th-note hats and
    periodic risers/impacts.  Faster and more aggressive than the old phonk
    beat, with no samples.
    """
    n = int(duration * sample_rate)
    mix = [0.0] * n
    rng = random.Random(seed)

    step_duration = 60.0 / bpm / 4.0
    steps = int(duration / step_duration)

    kick_steps = {0, 3, 4, 8, 11, 12}
    snare_steps = {4, 12}
    ghost_snare_steps = {7, 15}
    bass_pattern = {
        0: F1, 2: F1, 4: AB1, 6: C2,
        8: F1, 10: AB1, 12: C2, 14: EB2,
    }
    stab_steps = {2, 6, 10, 14}
    lead_steps = {5: C5, 13: EB5}

    for step in range(steps):
        start = int(step * step_duration * sample_rate)
        if start >= n:
            break
        bar_step = step % 16
        bar = step // 16

        if bar_step in kick_steps:
            _add_kick(mix, start, 0.95, sample_rate)
        if bar_step in snare_steps:
            _add_snare(mix, start, 0.50, sample_rate, rng)
        elif bar_step in ghost_snare_steps:
            _add_snare(mix, start, 0.18, sample_rate, rng)

        # Driving 16th hats with accented offbeat open hats.
        if bar_step % 2 == 1:
            _add_hat(mix, start, 0.10, sample_rate, rng)
        if bar_step in {2, 6, 10, 14}:
            _add_hat(
                mix, start, 0.14, sample_rate, rng, open_hat=True
            )

        if bar_step in bass_pattern:
            _add_stab_bass(
                mix, start, bass_pattern[bar_step], 0.62, sample_rate
            )
        if bar_step in stab_steps:
            chord = (
                [F3, AB3, C4, EB4] if bar % 4 == 3 else [F3, AB3, C4]
            )
            _add_string_stab(mix, start, chord, 0.11, sample_rate)
        if bar_step in lead_steps:
            _add_pluck(
                mix,
                start,
                lead_steps[bar_step],
                0.14,
                sample_rate,
                decay=5.0,
            )

        # A riser into every fourth bar and an impact on its downbeat.
        if bar_step == 8 and bar % 4 == 0:
            _add_noise_sweep(mix, start, 1.2, 0.05, sample_rate, rng)
        if bar_step == 0 and bar % 4 == 3:
            _add_snare(mix, start, 0.35, sample_rate, rng)

    _add_pad_chord(
        mix, sample_rate, [F3, AB3, C4], amp=0.04, lfo_rate=0.12
    )
    _add_crackle(mix, sample_rate, rng, density=0.00003)
    return _finalize(mix, sample_rate)


def synthesize_nightlife(
    duration: float = DEFAULT_DURATION,
    bpm: float = 116.0,
    seed: int = 1,
    sample_rate: int = SAMPLE_RATE,
) -> List[float]:
    """Four-on-the-floor synthwave groove for neon/nightlife topics."""
    n = int(duration * sample_rate)
    mix = [0.0] * n
    rng = random.Random(seed)

    step_duration = 60.0 / bpm / 4.0
    steps = int(duration / step_duration)

    kick_steps = {0, 4, 8, 12}
    snare_steps = {4, 12}
    bass_pattern = {0: F1, 2: F1, 6: AB1, 8: C2, 10: C2, 14: EB2}
    pluck_pattern = {
        1: F4, 3: AB4, 5: C5, 7: EB5,
        9: F4, 11: AB4, 13: C5, 15: EB5,
    }

    for step in range(steps):
        start = int(step * step_duration * sample_rate)
        if start >= n:
            break
        bar_step = step % 16

        if bar_step in kick_steps:
            _add_kick(mix, start, 0.85, sample_rate)
        if bar_step in snare_steps:
            _add_snare(mix, start, 0.38, sample_rate, rng)
        if bar_step in {2, 6, 10, 14}:
            _add_hat(mix, start, 0.16, sample_rate, rng, open_hat=True)
        elif bar_step % 2 == 0:
            _add_hat(mix, start, 0.10, sample_rate, rng)
        if bar_step in bass_pattern:
            _add_bass(mix, start, bass_pattern[bar_step], 0.55, sample_rate)
        if bar_step in pluck_pattern:
            _add_pluck(
                mix, start, pluck_pattern[bar_step], 0.16, sample_rate
            )

    _add_pad_chord(
        mix, sample_rate, [F3, AB3, C4, EB4], amp=0.045, lfo_rate=0.09
    )
    _add_crackle(mix, sample_rate, rng, density=0.00004)
    return _finalize(mix, sample_rate)


def synthesize_tension(
    duration: float = DEFAULT_DURATION,
    bpm: float = 90.0,
    seed: int = 1,
    sample_rate: int = SAMPLE_RATE,
) -> List[float]:
    """Sparse heartbeat pulse and dissonant drone for suspense topics."""
    n = int(duration * sample_rate)
    mix = [0.0] * n
    rng = random.Random(seed)

    step_duration = 60.0 / bpm / 4.0
    steps = int(duration / step_duration)

    # A lub-dub heartbeat instead of a dance kick pattern.
    heartbeat_steps = {0, 2, 8, 10}

    for step in range(steps):
        start = int(step * step_duration * sample_rate)
        if start >= n:
            break
        bar_step = step % 16
        bar = step // 16

        if bar_step in heartbeat_steps:
            _add_kick(mix, start, 0.55, sample_rate)
        if bar % 2 == 1 and bar_step == 12:
            _add_cowbell(mix, start, 155.0, 0.07, sample_rate)
        if bar_step == 14:
            _add_hat(mix, start, 0.05, sample_rate, rng, open_hat=True)
        if bar_step == 8 and bar % 2 == 0:
            _add_noise_sweep(
                mix, start, 1.6, 0.055, sample_rate, rng
            )

    _add_drone(mix, sample_rate, [F1, B1], amp=0.11, tremolo_rate=0.04)
    _add_pad_chord(mix, sample_rate, [F3, B3], amp=0.035, lfo_rate=0.05)
    _add_crackle(mix, sample_rate, rng, density=0.00008)
    return _finalize(mix, sample_rate)


