def synthesize_style(
    style: str,
    duration: float = DEFAULT_DURATION,
    bpm: Optional[float] = None,
    seed: int = 1,
    sample_rate: int = SAMPLE_RATE,
) -> List[float]:
    """Synthesize one track for the requested mood."""
    name = str(style or "action").strip().lower()
    if name not in STYLE_PRESETS:
        raise ValueError(
            f"Unknown audio style '{style}'. Choose from {VALID_STYLES}."
        )
    tempo = float(bpm if bpm is not None else STYLE_PRESETS[name]["bpm"])

    if name == "action":
        return synthesize_action_thriller(
            duration=duration, bpm=tempo, seed=seed, sample_rate=sample_rate
        )
    if name == "nightlife":
        return synthesize_nightlife(
            duration=duration, bpm=tempo, seed=seed, sample_rate=sample_rate
        )
    if name == "tension":
        return synthesize_tension(
            duration=duration, bpm=tempo, seed=seed, sample_rate=sample_rate
        )
    return synthesize_fun(
        duration=duration, bpm=tempo, seed=seed, sample_rate=sample_rate
    )


def write_wav(
    path: str, samples: List[float], sample_rate: int = SAMPLE_RATE
) -> None:
    """Write mono 16-bit PCM."""
    pcm = array.array(
        "h",
        (
            int(max(-1.0, min(1.0, sample)) * 32767)
            for sample in samples
        ),
    )
    with wave.open(path, "wb") as handle:
        handle.setnchannels(1)
        handle.setsampwidth(2)
        handle.setframerate(sample_rate)
        handle.writeframes(pcm.tobytes())


def _encode_mp3(wav_path: str, mp3_path: str, ffmpeg_exe: str) -> bool:
    """Encode WAV to MP3.  Return False when the encoder is unavailable."""
    command = [
        ffmpeg_exe,
        "-y",
        "-hide_banner",
        "-loglevel",
        "error",
        "-i",
        wav_path,
        "-codec:a",
        "libmp3lame",
        "-b:a",
        "192k",
        "-ac",
        "2",
        mp3_path,
    ]
    try:
        subprocess.run(
            command,
            check=True,
            capture_output=True,
            timeout=120,
        )
        return os.path.isfile(mp3_path) and os.path.getsize(mp3_path) > 0
    except (OSError, subprocess.SubprocessError):
        return False


def generate_track(
    output_dir: str,
    style: str,
    index: int,
    duration: float = DEFAULT_DURATION,
    bpm: Optional[float] = None,
    ffmpeg_exe: Optional[str] = None,
    force: bool = False,
) -> str:
    """Generate one original track for a style and return its path."""
    style_name = str(style or "action").strip().lower()
    if style_name not in STYLE_PRESETS:
        raise ValueError(
            f"Unknown audio style '{style}'. Choose from {VALID_STYLES}."
        )
    preset = STYLE_PRESETS[style_name]
    os.makedirs(output_dir, exist_ok=True)
    base = f"{preset['prefix']}_{index}"
    mp3_path = os.path.join(output_dir, base + ".mp3")
    wav_path = os.path.join(output_dir, base + ".wav")

    if not force:
        if os.path.isfile(mp3_path) and os.path.getsize(mp3_path) > 0:
            return mp3_path
        if os.path.isfile(wav_path) and os.path.getsize(wav_path) > 0:
            return wav_path

    tempo = float(
        bpm
        if bpm is not None
        else preset["bpm"] + (index - 1) * preset["step"]
    )
    seed = 1000 + index + sum(ord(char) for char in style_name)
    log.info(
        "Synthesizing %s track %s (%.0fs, %.0f BPM)...",
        style_name,
        base,
        duration,
        tempo,
    )
    samples = synthesize_style(
        style_name, duration=duration, bpm=tempo, seed=seed
    )
    write_wav(wav_path, samples)

    if ffmpeg_exe:
        if _encode_mp3(wav_path, mp3_path, ffmpeg_exe):
            try:
                os.remove(wav_path)
            except OSError:
                pass
            return mp3_path
        log.warning("MP3 encoder unavailable; keeping WAV for %s", base)

    return wav_path


def ensure_original_audio(
    audio_dir: str,
    styles: Optional[List[str]] = None,
    duration: float = DEFAULT_DURATION,
    ffmpeg_exe: Optional[str] = None,
    force: bool = False,
    count: Optional[int] = None,
) -> List[str]:
    """Create the requested style tracks if they are missing.

    ``count`` overrides the per-style default from ``STYLE_PRESETS``.
    """
    selected = list(styles) if styles else list(STYLE_PRESETS)
    paths: List[str] = []
    for style in selected:
        style_name = str(style).strip().lower()
        if style_name not in STYLE_PRESETS:
            raise ValueError(
                f"Unknown audio style '{style}'. "
                f"Choose from {VALID_STYLES}."
            )
        preset = STYLE_PRESETS[style_name]
        track_count = int(count if count is not None else preset["count"])
        for index in range(1, max(1, track_count) + 1):
            paths.append(
                generate_track(
                    audio_dir,
                    style_name,
                    index,
                    duration=duration,
                    ffmpeg_exe=ffmpeg_exe,
                    force=force,
                )
            )
    return paths


def main() -> None:
    logging.basicConfig(level=logging.INFO, format="%(levelname)s | %(message)s")
    parser = argparse.ArgumentParser(
        description="Generate original copyright-safe background music."
    )
    parser.add_argument(
        "--output-dir",
        default=os.path.join("assets", "audio"),
        help="Directory for generated tracks (default: assets/audio)",
    )
    parser.add_argument(
        "--styles",
        default="all",
        help=(
            "Comma-separated moods (action,nightlife,tension,fun) or 'all' "
            "(default: all)"
        ),
    )
    parser.add_argument(
        "--count",
        type=int,
        default=0,
        help="Override how many tracks to generate per style",
    )
    parser.add_argument("--duration", type=float, default=DEFAULT_DURATION)
    parser.add_argument(
        "--force",
        action="store_true",
        help="Regenerate tracks even when they already exist",
    )
    args = parser.parse_args()

    if args.styles.strip().lower() == "all":
        styles = list(STYLE_PRESETS)
    else:
        styles = [
            item.strip().lower()
            for item in args.styles.split(",")
            if item.strip()
        ]
    unknown = [style for style in styles if style not in STYLE_PRESETS]
    if unknown:
        parser.error(
            f"Unknown style(s): {', '.join(unknown)}. "
            f"Choose from {', '.join(VALID_STYLES)}."
        )

    ffmpeg_exe = None
    try:
        from utils import get_ffmpeg_exe

        ffmpeg_exe = get_ffmpeg_exe()
    except Exception as exc:  # pragma: no cover - environment-dependent
        log.warning("FFmpeg not available; WAV files will be used: %s", exc)

    for path in ensure_original_audio(
        args.output_dir,
        styles=styles,
        count=args.count or None,
        duration=args.duration,
        ffmpeg_exe=ffmpeg_exe,
        force=args.force,
    ):
        print(path)


if __name__ == "__main__":
    main()
